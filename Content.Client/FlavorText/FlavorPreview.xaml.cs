namespace Content.Client.FlavorText;

/// <summary>
/// Arcane - shows a character's flavor text the way other players see it in the detail examine window.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class FlavorPreview : Control
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IUriOpener _uri = default!;

    private const int NsfwTab = 3;
    private const int MaxLinkTextLength = 40;

    /// <summary>
    /// Link prefixes that are shown as clickable buttons, everything else is plain text.
    /// </summary>
    private static readonly string[] AllowedLinks =
    [
        "https://docs.google.com",
        "https://disk.yandex.by",
        "https://disk.yandex.ru",
        "https://docs.yandex.by",
        "https://docs.yandex.ru",
        "https://ru.imgbb.com",
        "https://ibb.co",
        "https://gyazo.com",
        "https://i.gyazo.com",
        "https://e621.net",
        "https://static1.e621.net",
        "https://e926.net",
        "https://static1.e926.net",
        "https://steamcommunity.com/id/",
        "https://steamcommunity.com/sharedfiles",
        "https://images.steamusercontent.com",
        "https://media.discordapp.net/attachments",
        "https://cdn.discordapp.com/attachments",
        "https://eblo.id", // Arcane
    ];

    private static readonly Direction[] Directions = [Direction.East, Direction.North, Direction.West, Direction.South];

    private int _direction = 3;
    private string _flavor = string.Empty;
    private ExtendedFlavorText _extended = new();
    private bool _showNsfw;

    public FlavorPreview()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Tabs.SetTabTitle(0, Loc.GetString("flavor-tab-flavor"));
        Tabs.SetTabTitle(1, Loc.GetString("flavor-tab-character"));
        Tabs.SetTabTitle(2, Loc.GetString("flavor-tab-gyr"));
        Tabs.SetTabTitle(NsfwTab, Loc.GetString("flavor-tab-nsfw"));
        Tabs.OnTabChanged += _ => UpdateFooter();

        RotateLeftButton.OnPressed += _ => Rotate(-1);
        RotateRightButton.OnPressed += _ => Rotate(1);
        CharacterView.OverrideDirection = Directions[_direction];
    }

    public void SetEntity(EntityUid? uid)
    {
        CharacterView.SetEntity(uid);
    }

    public void SetCharacter(string name, ProtoId<SpeciesPrototype> species, Sex sex, Gender gender)
    {
        var speciesName = _proto.TryIndex(species, out var speciesProto) ? Loc.GetString(speciesProto.Name) : species.Id;
        var sexName = Loc.GetString($"humanoid-profile-editor-sex-{sex.ToString().ToLowerInvariant()}-text");
        var genderName = Loc.GetString($"humanoid-profile-editor-pronouns-{gender.ToString().ToLowerInvariant()}-text");

        NameLabel.Text = name;
        DetailsLabel.Text = $"{speciesName} | {sexName} | {genderName}";
    }

    public void SetFlavor(string flavor, ExtendedFlavorText extended, bool showNsfw)
    {
        _flavor = flavor;
        _extended = extended;
        _showNsfw = showNsfw && _cfg.GetCVar(ArcaneCVars.FlavorNsfwEnabled) && _cfg.GetCVar(ArcaneCVars.NsfwContentEnabled);

        var showCharacter = _cfg.GetCVar(ArcaneCVars.FlavorTraitsEnabled);
        var showPreferences = _cfg.GetCVar(ArcaneCVars.FlavorGyrEnabled);

        Tabs.SetTabVisible(1, showCharacter);
        Tabs.SetTabVisible(2, showPreferences);
        Tabs.SetTabVisible(NsfwTab, _showNsfw);
        if (!Tabs.GetTabVisible(Tabs.CurrentTab))
            Tabs.CurrentTab = 0;

        SetText(AppearanceText, flavor, "detail-examinable-empty-flavor");
        SetText(CharacterText, extended.Character, "detail-examinable-empty-character");
        SetText(NsfwText, extended.Nsfw, "detail-examinable-empty-nsfw");

        PreferencesContainer.RemoveAllChildren();
        AddPreferences("humanoid-profile-editor-gyr-green", Color.Green, extended.Green, "detail-examinable-empty-green");
        AddPreferences("humanoid-profile-editor-gyr-yellow", Color.Yellow, extended.Yellow, "detail-examinable-empty-yellow");
        AddPreferences("humanoid-profile-editor-gyr-red", Color.Red, extended.Red, "detail-examinable-empty-red");

        UpdateFooter();
    }

    /// <summary>
    /// OOC notes, links and tags switch to their NSFW versions while the NSFW tab is open.
    /// </summary>
    private void UpdateFooter()
    {
        var nsfw = _showNsfw && Tabs.CurrentTab == NsfwTab;
        var showOoc = _cfg.GetCVar(ArcaneCVars.FlavorOocEnabled);
        var showLinks = _cfg.GetCVar(ArcaneCVars.FlavorLinksEnabled);

        OocBox.Visible = showOoc;
        TagsStripe.Visible = showOoc;
        LinksBox.Visible = showLinks;

        SetText(OocText, nsfw ? _extended.NsfwOoc : _extended.Ooc, "detail-examinable-empty-ooc");
        TagsLabel.Text = nsfw ? _extended.NsfwTags : _extended.Tags;
        FillLinks(nsfw ? _extended.NsfwLinks : _extended.Links);
    }

    private void Rotate(int step)
    {
        _direction = (_direction + step + Directions.Length) % Directions.Length;
        CharacterView.OverrideDirection = Directions[_direction];
    }

    private static void SetText(RichTextLabel label, string text, string emptyKey)
    {
        var markup = string.IsNullOrWhiteSpace(text)
            ? Loc.GetString(emptyKey)
            : ExtendedFlavorText.SanitizeMarkup(text);

        label.SetMessage(FormattedMessage.FromMarkupPermissive(markup));
    }

    private void AddPreferences(string titleKey, Color color, string text, string emptyKey)
    {
        var stripe = new StripeBack();
        stripe.AddChild(new Label
        {
            Text = Loc.GetString(titleKey),
            StyleClasses = { StyleNano.StyleClassLabelBig },
            Align = Label.AlignMode.Center,
            FontColorOverride = color,
        });
        PreferencesContainer.AddChild(stripe);

        var label = new RichTextLabel { Margin = new Thickness(0, 0, 0, 10) };
        SetText(label, text, emptyKey);
        PreferencesContainer.AddChild(label);
    }

    private void FillLinks(string links)
    {
        LinksContainer.RemoveAllChildren();

        var entries = ExtendedFlavorText.SplitList(links);
        if (entries.Length == 0)
        {
            LinksContainer.AddChild(new Label
            {
                Text = Loc.GetString("detail-examinable-empty-links"),
                HorizontalAlignment = HAlignment.Center,
                FontColorOverride = Color.Gray,
            });
            return;
        }

        foreach (var link in entries)
        {
            if (!IsAllowedLink(link))
            {
                LinksContainer.AddChild(new Label
                {
                    Text = link,
                    HorizontalAlignment = HAlignment.Center,
                    FontColorOverride = Color.Gray,
                });
                continue;
            }

            var button = new Button
            {
                Text = link.Length > MaxLinkTextLength ? link[..(MaxLinkTextLength - 3)] + "..." : link,
                ToolTip = Loc.GetString("humanoid-profile-editor-link-tooltip", ("url", link)),
                HorizontalAlignment = HAlignment.Center,
                StyleClasses = { StyleClass.ButtonOpenBoth },
            };
            button.OnPressed += _ => _uri.OpenUri(link);
            LinksContainer.AddChild(button);
        }
    }

    private static bool IsAllowedLink(string link)
    {
        foreach (var prefix in AllowedLinks)
        {
            if (link.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
                return true;
        }

        return false;
    }
}
