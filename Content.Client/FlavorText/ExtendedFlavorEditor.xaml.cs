using Content.Arcane.Common.CCVar;
using Content.Arcane.Common.Preferences;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Utility;

namespace Content.Client.FlavorText;

/// <summary>
/// Arcane - profile editor tab for the flavor text and its extended sections, with a live preview.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ExtendedFlavorEditor : Control
{
    [Dependency] private IConfigurationManager _cfg = default!;

    public event Action<string>? OnFlavorTextChanged;
    public event Action<ExtendedFlavorText>? OnExtendedChanged;

    public readonly TextEdit CFlavorTextInput;
    public readonly FlavorPreview Preview = new();

    private readonly Dictionary<TextEdit, Func<ExtendedFlavorText, string>> _getters = new();
    private ExtendedFlavorText _extended = new();
    private string _flavor = string.Empty;

    public ExtendedFlavorEditor()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        var showLinks = _cfg.GetCVar(ArcaneCVars.FlavorLinksEnabled);
        var showNsfw = _cfg.GetCVar(ArcaneCVars.FlavorNsfwEnabled) && _cfg.GetCVar(ArcaneCVars.NsfwContentEnabled);

        var appearance = AddTab("flavor-tab-flavor");
        CFlavorTextInput = AddSection(appearance, "humanoid-profile-editor-flavor-label", "flavor-text-placeholder-trauma", "#30D5C855", true);
        CFlavorTextInput.OnTextChanged += _ =>
        {
            _flavor = Collapse(CFlavorTextInput);
            OnFlavorTextChanged?.Invoke(_flavor);
            UpdatePreview();
        };

        var character = AddTab("flavor-tab-character", _cfg.GetCVar(ArcaneCVars.FlavorTraitsEnabled));
        AddField(character, "humanoid-profile-editor-flavor-character-label", "character-flavor-text-placeholder", "#30D5C855", true,
            f => f.Character, (f, v) => f.Character = v);

        var ooc = AddTab("flavor-tab-ooc-flavor", _cfg.GetCVar(ArcaneCVars.FlavorOocEnabled));
        AddField(ooc, "humanoid-profile-editor-flavor-ooc-label", "ooc-flavor-text-placeholder", "#80008055", true,
            f => f.Ooc, (f, v) => f.Ooc = v);
        AddField(ooc, "humanoid-profile-editor-flavor-tags-label", "tags-flavor-text-placeholder", "#9370DB55", false,
            f => f.Tags, (f, v) => f.Tags = v);
        if (showLinks)
        {
            AddField(ooc, "humanoid-profile-editor-flavor-links-label", "links-flavor-text-placeholder", "#00FA9A55", false,
                f => f.Links, (f, v) => f.Links = v);
        }

        var preferences = AddTab("flavor-tab-gyr", _cfg.GetCVar(ArcaneCVars.FlavorGyrEnabled));
        AddField(preferences, "humanoid-profile-editor-flavor-green-label", "green-flavor-text-placeholder", "#FFD70055", true,
            f => f.Green, (f, v) => f.Green = v);
        AddField(preferences, "humanoid-profile-editor-flavor-yellow-label", "yellow-flavor-text-placeholder", "#FFFF0055", true,
            f => f.Yellow, (f, v) => f.Yellow = v);
        AddField(preferences, "humanoid-profile-editor-flavor-red-label", "red-flavor-text-placeholder", "#FF000055", true,
            f => f.Red, (f, v) => f.Red = v);

        var nsfw = AddTab("flavor-tab-nsfw", showNsfw);
        AddField(nsfw, "humanoid-profile-editor-flavor-nsfw-label", "nsfw-flavor-text-placeholder", "#FF69B455", true,
            f => f.Nsfw, (f, v) => f.Nsfw = v);

        var nsfwOoc = AddTab("flavor-tab-nsfw-ooc-flavor", showNsfw);
        AddField(nsfwOoc, "humanoid-profile-editor-flavor-nsfw-ooc-label", "ooc-flavor-text-placeholder", "#80008055", true,
            f => f.NsfwOoc, (f, v) => f.NsfwOoc = v);
        AddField(nsfwOoc, "humanoid-profile-editor-flavor-nsfw-tags-label", "tags-flavor-text-placeholder", "#9370DB55", false,
            f => f.NsfwTags, (f, v) => f.NsfwTags = v);
        if (showLinks)
        {
            AddField(nsfwOoc, "humanoid-profile-editor-flavor-nsfw-links-label", "links-flavor-text-placeholder", "#00FA9A55", false,
                f => f.NsfwLinks, (f, v) => f.NsfwLinks = v);
        }

        Tabs.AddChild(Preview);
        Tabs.SetTabTitle(Tabs.ChildCount - 1, Loc.GetString("flavor-tab-preview"));
    }

    /// <summary>
    /// Fills every field from the profile without raising change events.
    /// </summary>
    public void SetFlavor(string flavor, ExtendedFlavorText extended)
    {
        _flavor = flavor;
        _extended = extended;

        CFlavorTextInput.TextRope = new Rope.Leaf(flavor);
        foreach (var (edit, getter) in _getters)
        {
            edit.TextRope = new Rope.Leaf(getter(extended));
        }

        UpdatePreview();
    }

    private void UpdatePreview()
    {
        Preview.SetFlavor(_flavor, _extended, true);
    }

    private BoxContainer AddTab(string titleKey, bool visible = true)
    {
        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalExpand = true,
        };

        Tabs.AddChild(box);
        Tabs.SetTabTitle(Tabs.ChildCount - 1, Loc.GetString(titleKey));
        Tabs.SetTabVisible(Tabs.ChildCount - 1, visible);
        return box;
    }

    private void AddField(
        BoxContainer tab,
        string labelKey,
        string placeholderKey,
        string color,
        bool expand,
        Func<ExtendedFlavorText, string> getter,
        Action<ExtendedFlavorText, string> setter)
    {
        var edit = AddSection(tab, labelKey, placeholderKey, color, expand);
        _getters[edit] = getter;

        edit.OnTextChanged += _ =>
        {
            var changed = _extended.Clone();
            setter(changed, Collapse(edit));
            _extended = changed;
            OnExtendedChanged?.Invoke(changed);
            UpdatePreview();
        };
    }

    private static TextEdit AddSection(BoxContainer tab, string labelKey, string placeholderKey, string color, bool expand)
    {
        var edit = new TextEdit
        {
            MinSize = new(110, expand ? 100 : 60),
            Margin = new Thickness(10),
            HorizontalExpand = true,
            VerticalExpand = expand,
            Placeholder = new Rope.Leaf(Loc.GetString(placeholderKey)),
        };

        var stripe = new StripeBack();
        stripe.AddChild(new Label
        {
            Text = Loc.GetString(labelKey),
            StyleClasses = { "LabelBig" },
            Margin = new Thickness(5, 0, 0, 0),
        });

        var inset = new PanelContainer
        {
            StyleClasses = { "Inset" },
            Margin = new Thickness(5),
            HorizontalExpand = true,
            VerticalExpand = expand,
        };
        inset.AddChild(edit);

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalExpand = expand,
        };
        content.AddChild(stripe);
        content.AddChild(inset);

        var bar = new PanelContainer
        {
            MinSize = new(5, 0),
            VerticalExpand = true,
            PanelOverride = new StyleBoxFlat { BackgroundColor = Color.FromHex(color) },
        };

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            VerticalExpand = expand,
        };
        row.AddChild(bar);
        row.AddChild(content);
        tab.AddChild(row);

        return edit;
    }

    private static string Collapse(TextEdit edit)
    {
        return Rope.Collapse(edit.TextRope).Trim();
    }
}
