namespace Content.Client.Options.UI.Tabs;

[GenerateTypedNameReferences]
public sealed partial class CustomizationTab : Control
{
    [Dependency] private IConfigurationManager _configuration = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IResourceCache _resources = default!;

    public CustomizationTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Control.AddOptionCheckBox(ArcaneCVars.ChatRunechat, UseRunechat);
        var fontOptions = GetRunechatFontOptions();
        var normalFont = Control.AddOptionDropDown(ArcaneCVars.ChatRunechatFont, RunechatFontDropDown, fontOptions);
        var whisperFont = Control.AddOptionDropDown(ArcaneCVars.ChatRunechatWhisperFont, RunechatWhisperFontDropDown, fontOptions);
        Control.AddOption(new OptionRunechatFontSize(Control, _configuration, ArcaneCVars.ChatRunechatFontSize, RunechatFontSizeSlider));
        Control.AddOption(new OptionRunechatFontSize(Control, _configuration, ArcaneCVars.ChatRunechatWhisperFontSize, RunechatWhisperFontSizeSlider));

        var randomColors = Control.AddOptionCheckBox(ArcaneCVars.ChatRunechatRandomColor, UseRandomRunechatColors);
        var typingAnimation = Control.AddOptionCheckBox(ArcaneCVars.ChatRunechatTypingAnimation, UseRunechatTypingAnimation);
        Control.AddOptionCheckBox(ArcaneCVars.ChatRunechatOutline, UseRunechatOutline);
        Control.AddOption(new OptionRunechatColor(Control, _configuration, RunechatColorSlider));
        Control.AddOption(new OptionRunechatFloat(Control, _configuration, ArcaneCVars.ChatRunechatTypingSpeed, RunechatTypingSpeedSlider, RunechatSheetlet.MinimumTypingSpeed, RunechatSheetlet.MaximumTypingSpeed));
        Control.AddOption(new OptionRunechatFloat(Control, _configuration, ArcaneCVars.ChatRunechatPostTypingLifetime, RunechatPostTypingLifetimeSlider, RunechatSheetlet.MinimumPostTypingLifetime, RunechatSheetlet.MaximumPostTypingLifetime));

        normalFont.ImmediateValueChanged += font => UpdateRunechatFontPreview(RunechatFontPreview, font);
        whisperFont.ImmediateValueChanged += font => UpdateRunechatFontPreview(RunechatWhisperFontPreview, font);
        randomColors.ImmediateValueChanged += _ => UpdateRunechatSettingsVisibility();
        typingAnimation.ImmediateValueChanged += _ => UpdateRunechatSettingsVisibility();

        Control.AddOptionCheckBox(ArcaneCVars.UseCustomRadioChannelColors, UseCustomRadioChannelColors);
        Control.AddOption(new OptionRadioChannelColors(Control, _configuration, _prototypes, RadioChannelColorsContainer));

        Control.AddOptionCheckBox(ArcaneCVars.UseCustomInteractionOutlineColors, UseCustomInteractionOutlineColors);
        Control.AddOptionColorSlider(ArcaneCVars.ValidInteractionOutlineColor, ValidInteractionOutlineColorSlider);
        Control.AddOptionColorSlider(ArcaneCVars.InvalidInteractionOutlineColor, InvalidInteractionOutlineColorSlider);

        Control.Initialize();
        UpdateRunechatFontPreview(RunechatFontPreview, _configuration.GetCVar(ArcaneCVars.ChatRunechatFont));
        UpdateRunechatFontPreview(RunechatWhisperFontPreview, _configuration.GetCVar(ArcaneCVars.ChatRunechatWhisperFont));
        UpdateRunechatSettingsVisibility();
    }

    private IReadOnlyCollection<OptionDropDownCVar<string>.ValueOption> GetRunechatFontOptions()
    {
        return
        [
            new OptionDropDownCVar<string>.ValueOption(RunechatSheetlet.Grand9kFontId, Loc.GetString("ui-options-runechat-font-grand9k")),
            new OptionDropDownCVar<string>.ValueOption(RunechatSheetlet.PressStart2PFontId, Loc.GetString("ui-options-runechat-font-press-start-2p")),
            new OptionDropDownCVar<string>.ValueOption(RunechatSheetlet.Tiny5FontId, Loc.GetString("ui-options-runechat-font-tiny5")),
        ];
    }

    private void UpdateRunechatFontPreview(Label preview, string fontId)
    {
        var normalizedFontId = RunechatSheetlet.NormalizeFontId(fontId);
        preview.Text = normalizedFontId switch
        {
            RunechatSheetlet.PressStart2PFontId => Loc.GetString("ui-options-runechat-font-press-start-2p"),
            RunechatSheetlet.Tiny5FontId => Loc.GetString("ui-options-runechat-font-tiny5"),
            _ => Loc.GetString("ui-options-runechat-font-grand9k"),
        };
        var font = _resources.GetResource<FontResource>(RunechatSheetlet.GetFontPath(normalizedFontId));
        preview.Stylesheet = RunechatSheetlet.CreateLabelFontStylesheet(font, 12);
    }

    private void UpdateRunechatSettingsVisibility()
    {
        var randomColors = UseRandomRunechatColors.Pressed;
        RunechatColorSlider.Slider.Visible = !randomColors;
        RunechatColorSlider.ExampleLabel.Visible = !randomColors;
        RunechatTypingSpeedSlider.Slider.Disabled = !UseRunechatTypingAnimation.Pressed;
        RunechatPostTypingLifetimeSlider.Slider.Disabled = !UseRunechatTypingAnimation.Pressed;
    }

    private sealed class OptionRunechatColor : BaseOptionCVar<string>
    {
        private readonly OptionColorSlider _slider;

        protected override string Value
        {
            get => _slider.Slider.Color.ToHex();
            set
            {
                var color = RunechatSheetlet.NormalizeTextColor(value);
                _slider.Slider.Color = color;
                _slider.ExampleLabel.FontColorOverride = color;
            }
        }

        public OptionRunechatColor(
            OptionsTabControlRow controller,
            IConfigurationManager configuration,
            OptionColorSlider slider)
            : base(controller, configuration, ArcaneCVars.ChatRunechatColor)
        {
            _slider = slider;
            slider.Slider.OnColorChanged += _ => ValueChanged();
        }
    }

    private sealed class OptionRunechatFloat : BaseOptionCVar<float>
    {
        private readonly OptionSlider _slider;
        private readonly float _minimum;
        private readonly float _maximum;
        private readonly float _defaultValue;

        protected override float Value
        {
            get => _slider.Slider.Value;
            set => _slider.Slider.Value = RunechatSheetlet.NormalizeFloat(value, _defaultValue, _minimum, _maximum);
        }

        public OptionRunechatFloat(
            OptionsTabControlRow controller,
            IConfigurationManager configuration,
            CVarDef<float> cVar,
            OptionSlider slider,
            float minimum,
            float maximum)
            : base(controller, configuration, cVar)
        {
            _slider = slider;
            _minimum = minimum;
            _maximum = maximum;
            _defaultValue = cVar.DefaultValue;

            slider.Slider.MinValue = minimum;
            slider.Slider.MaxValue = maximum;
            slider.Slider.OnValueChanged += _ => ValueChanged();
        }
    }

    private sealed class OptionRunechatFontSize : BaseOptionCVar<float>
    {
        private readonly OptionSlider _slider;
        private readonly float _defaultValue;

        protected override float Value
        {
            get => _slider.Slider.Value;
            set => _slider.Slider.Value = RunechatSheetlet.NormalizeFontSize(value, _defaultValue);
        }

        public OptionRunechatFontSize(
            OptionsTabControlRow controller,
            IConfigurationManager configuration,
            CVarDef<float> cVar,
            OptionSlider slider)
            : base(controller, configuration, cVar)
        {
            _slider = slider;
            _defaultValue = cVar.DefaultValue;

            slider.Slider.MinValue = RunechatSheetlet.MinimumFontSize;
            slider.Slider.MaxValue = RunechatSheetlet.MaximumFontSize;
            slider.Slider.Rounded = true;
            slider.Slider.OnValueChanged += _ => ValueChanged();
        }

    }
}

public sealed class OptionRadioChannelColors : BaseOption
{
    private readonly IConfigurationManager _configuration;
    private readonly List<(RadioChannelPrototype Channel, OptionColorSlider Slider)> _sliders = [];

    public OptionRadioChannelColors(
        OptionsTabControlRow controller,
        IConfigurationManager configuration,
        IPrototypeManager prototypes,
        BoxContainer container)
        : base(controller)
    {
        _configuration = configuration;

        foreach (var channel in prototypes.EnumeratePrototypes<RadioChannelPrototype>().OrderBy(channel => channel.LocalizedName))
        {
            var slider = new OptionColorSlider
            {
                Title = channel.LocalizedName,
                Example = Loc.GetString("ui-options-radio-channel-colors-example", ("channel", channel.LocalizedName)),
            };

            slider.Slider.OnColorChanged += _ =>
            {
                slider.ExampleLabel.FontColorOverride = slider.Slider.Color.WithAlpha(1f);
                ValueChanged();
            };
            container.AddChild(slider);
            _sliders.Add((channel, slider));
        }
    }

    public override void LoadValue()
    {
        var overrides = RadioChannelColorSystem.Parse(_configuration.GetCVar(ArcaneCVars.RadioChannelColors));
        foreach (var (channel, slider) in _sliders)
        {
            var color = overrides.GetValueOrDefault(channel.ID, channel.Color);
            slider.Slider.Color = color;
            slider.ExampleLabel.FontColorOverride = color.WithAlpha(1f);
        }
    }

    public override void SaveValue()
    {
        _configuration.SetCVar(ArcaneCVars.RadioChannelColors, GetUiValue());
    }

    public override void ResetToDefault()
    {
        foreach (var (channel, slider) in _sliders)
        {
            slider.Slider.Color = channel.Color;
            slider.ExampleLabel.FontColorOverride = channel.Color.WithAlpha(1f);
        }
    }

    public override bool IsModified()
    {
        return GetUiValue() != Normalize(_configuration.GetCVar(ArcaneCVars.RadioChannelColors));
    }

    public override bool IsModifiedFromDefault()
    {
        return GetUiValue().Length > 0;
    }

    private string GetUiValue()
    {
        var colors = new List<KeyValuePair<string, Color>>();
        foreach (var (channel, slider) in _sliders)
        {
            var color = slider.Slider.Color;
            if (color.ToHex() != channel.Color.ToHex())
                colors.Add(new KeyValuePair<string, Color>(channel.ID, color));
        }

        return RadioChannelColorSystem.Serialize(colors);
    }

    private string Normalize(string value)
    {
        var overrides = RadioChannelColorSystem.Parse(value);
        var colors = new List<KeyValuePair<string, Color>>();
        foreach (var (channel, _) in _sliders)
        {
            if (overrides.TryGetValue(channel.ID, out var color) && color.ToHex() != channel.Color.ToHex())
                colors.Add(new KeyValuePair<string, Color>(channel.ID, color));
        }

        return RadioChannelColorSystem.Serialize(colors);
    }
}
