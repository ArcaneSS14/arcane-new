using Content.Client.Options.UI.Tabs;
using Content.Client.Administration.Managers;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.UserInterface.Controls; // Arcane

namespace Content.Client.Options.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class OptionsMenu : DefaultWindow
    {
        [Dependency] private IClientAdminManager _adminManager = default!;

        public OptionsMenu()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            // Arcane-Edit-Start: consolidate the eight positional title assignments.
            ReloadLocalization();
            // Arcane-Edit-End

            UpdateTabs();
        }

        // Arcane-Start
        public void ReloadLocalization()
        {
            Title = Loc.GetString("ui-options-title");
            TabContainer.SetTabTitle(MiscTab, Loc.GetString("ui-options-tab-misc"));
            TabContainer.SetTabTitle(GraphicsTab, Loc.GetString("ui-options-tab-graphics"));
            TabContainer.SetTabTitle(KeyRebindTab, Loc.GetString("ui-options-tab-controls"));
            TabContainer.SetTabTitle(AudioTab, Loc.GetString("ui-options-tab-audio"));
            TabContainer.SetTabTitle(AccessibilityTab, Loc.GetString("ui-options-tab-accessibility"));
            TabContainer.SetTabTitle(AdminOptionsTab, Loc.GetString("ui-options-tab-admin"));
            TabContainer.SetTabTitle(NetworkTab, Loc.GetString("ui-options-tab-network"));
            TabContainer.SetTabTitle(CustomizationTab, Loc.GetString("ui-options-tab-customization"));
            MiscTab.ReloadLocalization();
            GraphicsTab.ReloadLocalization();
            KeyRebindTab.ReloadLocalization();
            AudioTab.ReloadLocalization();
            AccessibilityTab.ReloadLocalization();
            AdminOptionsTab.ReloadLocalization();
            NetworkTab.ReloadLocalization();
            CustomizationTab.ReloadLocalization();
        }
        // Arcane-End

        public void UpdateTabs()
        {
            var isAdmin = _adminManager.IsAdmin(true);
            Tabs.SetTabVisible(5, isAdmin);

            GraphicsTab.Control.ReloadValues();
            MiscTab.Control.ReloadValues();
            AccessibilityTab.Control.ReloadValues();
            AudioTab.Control.ReloadValues();
            AdminOptionsTab.Control.ReloadValues();
            CustomizationTab.Control.ReloadValues(); // Arcane
        }
    }
}
