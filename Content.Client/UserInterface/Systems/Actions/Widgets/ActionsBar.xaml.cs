using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Content.Client.UserInterface.Systems.Actions.Controls; // Arcane

namespace Content.Client.UserInterface.Systems.Actions.Widgets;

[GenerateTypedNameReferences]
public sealed partial class ActionsBar : UIWidget
{
    // Arcane-Start
    public ActionButtonContainer ActionsContainer { get; private set; } = default!;
    public event Action? ContainerReplaced;

    public void ReplaceActionsContainer(ActionButtonContainer replacement)
    {
        var previous = ActionsContainer;
        var parent = previous.Parent!;
        replacement.HorizontalAlignment = previous.HorizontalAlignment;
        replacement.VerticalAlignment = previous.VerticalAlignment;
        // The screen sets the grid's flow limit; the old vertical bar's fixed width would hide overflow.
        replacement.Rows = Math.Max(1, previous.Rows);
        parent.RemoveChild(previous);
        parent.AddChild(replacement);
        ActionsContainer = replacement;
        ContainerReplaced?.Invoke();
    }
    // Arcane-End

    public ActionsBar()
    {
        RobustXamlLoader.Load(this);
        ActionsContainer = DefaultActionsContainer; // Arcane
    }
}
