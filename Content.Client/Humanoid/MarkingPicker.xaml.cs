using System.Linq;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

// Arcane-Start
using Content.Shared.CCVar;
using Content.Shared.Humanoid;
using Content.Shared.Humanoid.Markings;
using Robust.Shared.Configuration;
// Arcane-End

namespace Content.Client.Humanoid;

[GenerateTypedNameReferences]
public sealed partial class MarkingPicker : Control
{
    // Arcane-Start
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private MarkingManager _marking = default!;
    // Arcane-End
    private MarkingsViewModel? _markingsModel;

    public MarkingPicker()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        // Arcane-Start
        AnimatedPreview.OnToggled += args =>
        {
            if (_markingsModel != null)
                _markingsModel.AnimatedPreview = args.Pressed;
        };
        EarsAboveHairToggle.OnToggled += args => EarsAboveHairChanged?.Invoke(args.Pressed);
        // Arcane-End

        UpdateMarkings();
    }

    public void SetModel(MarkingsViewModel model)
    {
        // Arcane-Start
        if (_markingsModel != null)
        {
            _markingsModel.OrganDataChanged -= UpdateMarkings;
            _markingsModel.EnforcementsChanged -= UpdateMarkings;
            _markingsModel.MarkingsChanged -= OnMarkingsChanged;
            _markingsModel.MarkingsReset -= UpdateEarVisibility;
        }
        // Arcane-End
        _markingsModel = model;

        // Arcane-Start
        AnimatedPreview.Pressed = model.AnimatedPreview;
        OnReducedMotionChanged(_cfg.GetCVar(CCVars.ReducedMotion));
        // Arcane-End

        // Arcane-Edit-Start
        if (IsInsideTree)
        {
            _markingsModel.OrganDataChanged += UpdateMarkings;
            _markingsModel.EnforcementsChanged += UpdateMarkings;
            _markingsModel.MarkingsChanged += OnMarkingsChanged;
            _markingsModel.MarkingsReset += UpdateEarVisibility;
        }
        // Arcane-Edit-End
        UpdateMarkings(); // Arcane
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _cfg.OnValueChanged(CCVars.ReducedMotion, OnReducedMotionChanged, true); // Arcane

        _markingsModel?.OrganDataChanged += UpdateMarkings;
        _markingsModel?.EnforcementsChanged += UpdateMarkings;
        // Arcane-Start
        _markingsModel?.MarkingsChanged += OnMarkingsChanged;
        _markingsModel?.MarkingsReset += UpdateEarVisibility;
        // Arcane-End
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _cfg.UnsubValueChanged(CCVars.ReducedMotion, OnReducedMotionChanged); // Arcane

        _markingsModel?.OrganDataChanged -= UpdateMarkings;
        _markingsModel?.EnforcementsChanged -= UpdateMarkings;
        // Arcane-Start
        _markingsModel?.MarkingsChanged -= OnMarkingsChanged;
        _markingsModel?.MarkingsReset -= UpdateEarVisibility;
        // Arcane-End
    }

    // Arcane-Start
    private void OnReducedMotionChanged(bool reduced)
    {
        AnimatedPreview.Disabled = reduced;
        if (_markingsModel != null)
            _markingsModel.PreviewReducedMotion = reduced;
    }
    // Arcane-End

    private void UpdateMarkings()
    {
        if (_markingsModel is null)
            return;

        OrganTabs.RemoveAllChildren();

        var i = 0;
        foreach (var (organ, organData) in _markingsModel.OrganData)
        {
            var control = new OrganMarkingPicker(_markingsModel, organ, organData.Layers, organData.Group);
            if (control.Empty)
                continue;

            OrganTabs.AddChild(control);
            OrganTabs.SetTabTitle(i, Loc.GetString($"markings-organ-{organ.Id}"));
            i++;
        }

        if (i > 0)
            OrganTabs.CurrentTab = 0;
        OrganTabs.TabsVisible = i > 1;
        UpdateEarVisibility(); // Arcane
    }
}
