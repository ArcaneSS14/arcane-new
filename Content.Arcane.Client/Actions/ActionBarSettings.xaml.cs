using Content.Arcane.Common.Actions;
using Content.Client.Options.UI.Tabs;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Arcane.Client.Actions;

[GenerateTypedNameReferences]
public sealed partial class ActionBarSettings : BoxContainer
{
    public ActionBarSettings()
    {
        RobustXamlLoader.Load(this);
    }

    public void Bind(MiscTab tab, ActionsBarLayoutUIController layout)
    {
        tab.Control.AddOptionCheckBox(ActionBarCVars.LockDrag, LockDrag);
        tab.Control.AddOptionCheckBox(ActionBarCVars.FreePlacement, FreePlacement);
        ResetLayout.OnPressed += _ => layout.Reset();
    }
}
