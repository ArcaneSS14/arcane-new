using Content.Client.Research.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Arcane.Client.Research.UI;

[GenerateTypedNameReferences]
public sealed partial class FancyResearchConsoleLogWindow : ResearchJournalWindow
{
    public FancyResearchConsoleLogWindow()
    {
        RobustXamlLoader.Load(this);
    }

    public override void SetExperimentEntries(List<Control> entries)
    {
        ExperimentsContainer.RemoveAllChildren();

        foreach (var entry in entries)
        {
            ExperimentsContainer.AddChild(entry);
        }
    }

    public override void SetLogsMessage(FormattedMessage message)
    {
        LogsLabel.SetMessage(message);
    }
}
