using System.Linq;
using System.Numerics;
using Content.Client.Audio;
using Content.Arcane.Client.Radio;
using Content.Arcane.Common.CCVar;
using Content.Shared.Radio;
using Content.Shared.StatusIcon;
using Robust.Client;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.GameObjects;
using Robust.Shared.Localization;
using Robust.Shared.Maths;
using Robust.Shared.Prototypes;
using static Robust.Client.UserInterface.Controls.BoxContainer;

namespace Content.Arcane.Client.TTS;

[GenerateTypedNameReferences]
public sealed partial class TTSOptionsTab : Control
{
    [Dependency] private IConfigurationManager _cfg = default!;
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private ILocalizationManager _loc = default!;
    [Dependency] private IEntitySystemManager _entitySystem = default!;
    [Dependency] private IBaseClient _baseClient = default!;

    private SpriteSystem? _sprites;
    private readonly List<(TextureRect Rect, ProtoId<JobIconPrototype> Icon)> _channelIcons = new();
    private readonly TTSRadioMixerOption _mixer;

    private static readonly Color SeparatorColor = Color.FromHex("#3D4059");

    public TTSOptionsTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        Control.AddOptionPercentSlider(
            ArcaneCVars.TTSVolume,
            SliderVolumeTTS,
            scale: 1f);
        Control.AddOptionPercentSlider(
            ArcaneCVars.TTSRadioVolume,
            SliderVolumeRadioTTS,
            scale: 1f);
        Control.AddOptionCheckBox(ArcaneCVars.UseTTS, UseTTSCheckBox);

        _mixer = Control.AddOption(new TTSRadioMixerOption(Control, _cfg));
        PopulateChannelMixer();
        RefreshChannelIcons();

        Control.Initialize();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _entitySystem.SystemLoaded += OnSystemLoaded;
    }

    protected override void ExitedTree()
    {
        _entitySystem.SystemLoaded -= OnSystemLoaded;
        base.ExitedTree();
    }

    private void OnSystemLoaded(object? sender, SystemChangedArgs args)
    {
        if (args.System is not SpriteSystem)
            return;

        _sprites = null;
        RefreshChannelIcons();
    }

    public void RefreshChannelIcons()
    {
        if (_channelIcons.Count == 0)
            return;

        if (_sprites == null)
        {
            if (_baseClient.RunLevel < ClientRunLevel.Connected)
                return;

            _sprites = _entitySystem.GetEntitySystem<SpriteSystem>();
        }

        foreach (var (rect, iconId) in _channelIcons)
        {
            if (_prototypes.TryIndex(iconId, out var iconPrototype))
                rect.Texture = _sprites.Frame0(iconPrototype.Icon);
        }
    }

    private void PopulateChannelMixer()
    {
        AddChannelListHeader();

        var channels = _prototypes.EnumeratePrototypes<RadioChannelPrototype>()
            .Where(channel => channel.Frequency > 0)
            .OrderBy(channel => RadioChannelOrder.Channels.GetValueOrDefault(channel.ID, int.MaxValue))
            .ThenBy(channel => channel.Frequency)
            .ToList();

        for (var i = 0; i < channels.Count; i++)
        {
            AddChannelRow(channels[i]);
            if (i < channels.Count - 1)
                ChannelList.AddChild(MakeSeparator());
        }
    }

    private void AddChannelListHeader()
    {
        var header = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 2, 0, 2),
        };

        header.AddChild(new Control { MinWidth = 36 });
        header.AddChild(new Label { Text = _loc.GetString("ui-options-tts-radio-channel"), MinWidth = 170, StyleClasses = { "LabelHeading" } });
        header.AddChild(new Label { Text = _loc.GetString("ui-options-tts-radio-channel-enabled"), MinWidth = 24, HorizontalAlignment = HAlignment.Center, StyleClasses = { "LabelHeading" } });
        header.AddChild(new Control { HorizontalExpand = true });
        header.AddChild(new Label { Text = _loc.GetString("ui-options-tts-radio-channel-volume"), StyleClasses = { "LabelHeading" } });
        ChannelList.AddChild(header);
    }

    private void AddChannelRow(RadioChannelPrototype channel)
    {
        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 6, 0, 6),
            VerticalAlignment = VAlignment.Center,
        };

        var icon = new TextureRect
        {
            TextureScale = new Vector2(3, 3),
            VerticalAlignment = VAlignment.Center,
            HorizontalAlignment = HAlignment.Center,
            Margin = new Thickness(4, 0, 4, 0),
        };
        _channelIcons.Add((icon, channel.Icon));
        row.AddChild(icon);

        var nameLabel = new Label
        {
            Text = _loc.GetString(channel.Name),
            MinWidth = 170,
            VerticalAlignment = VAlignment.Center,
        };
        row.AddChild(nameLabel);

        var enabledCheckBox = new CheckBox
        {
            HorizontalAlignment = HAlignment.Center,
            VerticalAlignment = VAlignment.Center,
            MinWidth = 24,
            ToolTip = _loc.GetString("ui-options-tts-radio-channel-toggle-tooltip"),
        };
        row.AddChild(enabledCheckBox);

        var volumeSlider = new Slider
        {
            MinValue = 0f,
            MaxValue = 1f,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        };
        row.AddChild(volumeSlider);

        var volumeLabel = new Label
        {
            MinWidth = 40,
            Margin = new Thickness(6, 0, 0, 0),
            VerticalAlignment = VAlignment.Center,
        };
        row.AddChild(volumeLabel);

        _mixer.AddRow(channel.Frequency.Value, enabledCheckBox, volumeSlider, volumeLabel, FormatPercent);

        ChannelList.AddChild(row);
    }

    private static Control MakeSeparator()
    {
        return new PanelContainer
        {
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = SeparatorColor,
                ContentMarginBottomOverride = 2,
                ContentMarginLeftOverride = 2,
            },
            MinHeight = 1,
            Margin = new Thickness(0, 2, 0, 2),
        };
    }

    private string FormatPercent(float value)
    {
        return _loc.GetString("ui-options-value-percent", ("value", value));
    }
}
