using System.Linq;
using Content.Arcane.Shared.Power;
using Content.Client.UserInterface.Controls;
using Content.Shared.Atmos;
using Content.Shared.Atmos.EntitySystems;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Arcane.Client.Power;

[GenerateTypedNameReferences]
public sealed partial class SupermatterMonitorWindow : FancyWindow
{
    private readonly SharedAtmosphereSystem _atmosphere;
    private readonly Dictionary<Gas, Label> _gasLabels = [];
    private SupermatterMonitorEntry[] _entries = [];

    public event Action<NetEntity>? FocusSelected;

    public SupermatterMonitorWindow()
    {
        RobustXamlLoader.Load(this);
        _atmosphere = IoCManager.Resolve<IEntitySystemManager>().GetEntitySystem<SharedAtmosphereSystem>();
        CrystalSelection.OnItemSelected += args => FocusSelected?.Invoke(_entries[args.Id].Crystal);
    }

    public void UpdateReadings(SupermatterMonitorState state)
    {
        if (!_entries.SequenceEqual(state.Crystals))
        {
            _entries = state.Crystals;
            CrystalSelection.Clear();
            for (var index = 0; index < _entries.Length; index++)
            {
                var entry = _entries[index];
                CrystalSelection.AddItem(Loc.GetString("arcane-supermatter-monitor-crystal",
                    ("name", entry.Name), ("status", StatusName(entry.Status))), index);
            }
        }

        NoCrystals.Visible = _entries.Length == 0;
        CrystalSelection.Visible = _entries.Length > 0;
        Readings.Visible = state.Reading != null;
        if (state.Reading is not { } reading)
            return;

        var indexOfFocus = Array.FindIndex(_entries, entry => entry.Crystal == reading.Crystal);
        if (indexOfFocus >= 0)
            CrystalSelection.SelectId(indexOfFocus);

        Integrity.Text = Loc.GetString("arcane-supermatter-monitor-integrity", ("value", Round(reading.Integrity)));
        Power.Text = Loc.GetString("arcane-supermatter-monitor-power", ("value", Round(reading.Power)));
        Radiation.Text = Loc.GetString("arcane-supermatter-monitor-radiation", ("value", Round(reading.Radiation)));
        Moles.Text = Loc.GetString("arcane-supermatter-monitor-moles", ("value", Round(reading.Moles)));
        Temperature.Text = Loc.GetString("arcane-supermatter-monitor-temperature",
            ("value", Round(reading.Temperature)), ("limit", Round(reading.TemperatureLimit)));
        Waste.Text = Loc.GetString("arcane-supermatter-monitor-waste", ("value", Round(reading.Waste)));
        Absorption.Text = Loc.GetString("arcane-supermatter-monitor-absorption", ("value", Round(reading.Absorption)));

        foreach (var label in _gasLabels.Values)
            label.Visible = false;
        foreach (var gas in reading.Gases)
        {
            if (!_gasLabels.TryGetValue(gas.Gas, out var label))
            {
                label = new Label();
                _gasLabels.Add(gas.Gas, label);
                GasReadings.AddChild(label);
            }

            label.Text = Loc.GetString("arcane-supermatter-monitor-gas",
                ("name", Loc.GetString(_atmosphere.GetGas(gas.Gas).Name)), ("value", Round(gas.Proportion * 100f)));
            label.Visible = true;
        }
    }

    private static float Round(float value) => MathF.Round(value, 2);

    private static string StatusName(SupermatterMonitorStatus status) => Loc.GetString(status switch
    {
        SupermatterMonitorStatus.Normal => "supermatter-console-window-normal-status",
        SupermatterMonitorStatus.Warning => "supermatter-console-window-warning-status",
        SupermatterMonitorStatus.Emergency => "supermatter-console-window-emergency-status",
        SupermatterMonitorStatus.Delaminating => "supermatter-console-window-delaminating-status",
        _ => "supermatter-console-window-inactive-status",
    });
}
