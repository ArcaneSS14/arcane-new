using Content.Arcane.Shared.Economy;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Arcane.Client.Economy;

[GenerateTypedNameReferences]
public sealed partial class BankCardWindow : DefaultWindow
{
    public event Action<int>? OnWithdraw;

    private int _balance;

    public BankCardWindow()
    {
        RobustXamlLoader.Load(this);

        MaxButton.OnPressed += _ => AmountInput.Text = _balance.ToString();
        WithdrawButton.OnPressed += _ =>
        {
            if (int.TryParse(AmountInput.Text, out var amount) && amount > 0)
                OnWithdraw?.Invoke(amount);
        };
    }

    public void UpdateState(BankCardBoundUiState state)
    {
        _balance = state.Balance;
        AccountLabel.Text = state.AccountId is { } id
            ? Loc.GetString("bank-card-account", ("account", id))
            : Loc.GetString("bank-card-no-account");
        BalanceLabel.Text = Loc.GetString("bank-card-credits", ("amount", state.Balance));
        WithdrawButton.Disabled = state.AccountId == null || state.Balance <= 0;
        MaxButton.Disabled = WithdrawButton.Disabled;
    }
}
