using System.Linq;
using Content.Arcane.Shared.Species;
using Content.Client.Guidebook;
using Content.Client.Stylesheets;
using Content.Client.UserInterface.Controls;
using Content.Shared.Guidebook;
using Content.Shared.Humanoid;
using Content.Shared.Humanoid.Prototypes;
using Content.Shared.Preferences;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.ContentPack;
using Robust.Shared.Prototypes;

namespace Content.Arcane.Client.Lobby;

/// <summary>
/// Lists round-start species by category with a preview and their description (Orion #45).
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SpeciesWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IResourceManager _resources = default!;
    [Dependency] private DocumentParsingManager _parsing = default!;

    public event Action<ProtoId<SpeciesPrototype>>? OnSpeciesChosen;

    private readonly HumanoidCharacterProfile _profile;
    private readonly JobPrototype? _job;
    private readonly List<SpeciesButton> _buttons = new();
    private ProtoId<SpeciesPrototype> _selected;

    public SpeciesWindow(HumanoidCharacterProfile profile)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _profile = profile;
        var highJob = profile.JobPriorities.FirstOrDefault(x => x.Value == JobPriority.High).Key;
        if (highJob != default)
            _proto.TryIndex(highJob, out _job);

        Select.OnPressed += _ => OnSpeciesChosen?.Invoke(_selected);
        OnClose += () =>
        {
            Mob.ClearPreview();
            JobLoadout.ClearPreview();
        };

        var species = _proto.EnumeratePrototypes<SpeciesPrototype>()
            .Where(x => x.RoundStart)
            .OrderBy(x => Loc.GetString(x.Name), StringComparer.CurrentCultureIgnoreCase)
            .ToList();

        foreach (var category in Enum.GetValues<SpeciesCategory>())
        {
            var inCategory = species.Where(x => GetCategory(x.ID) == category).ToList();
            if (inCategory.Count == 0)
                continue;

            AddCategoryLabel(category);
            foreach (var item in inCategory)
            {
                var button = new SpeciesButton(item.ID)
                {
                    HorizontalExpand = true,
                    ToggleMode = true,
                    Text = Loc.GetString(item.Name),
                    Margin = new Thickness(5f),
                };
                button.OnPressed += _ => SelectSpecies(button.Species);
                _buttons.Add(button);
                SpeciesContainer.AddChild(button);
            }
        }

        SelectSpecies(profile.Species);
    }

    private SpeciesCategory GetCategory(string species)
    {
        return _proto.TryIndex<SpeciesInfoPrototype>(species, out var info) ? info.Category : SpeciesCategory.Classic;
    }

    private void AddCategoryLabel(SpeciesCategory category)
    {
        var container = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            Margin = new Thickness(5f),
        };
        container.AddChild(new Label
        {
            Text = Loc.GetString($"species-window-category-{category.ToString().ToLowerInvariant()}"),
            StyleClasses = { StyleClass.LabelSubText },
            HorizontalAlignment = HAlignment.Center,
            Margin = new Thickness(2f),
        });
        container.AddChild(new Separator { Margin = new Thickness(2f, 2f, 2f, 4f) });
        SpeciesContainer.AddChild(container);
    }

    private void SelectSpecies(ProtoId<SpeciesPrototype> species)
    {
        _selected = species;
        foreach (var button in _buttons)
        {
            button.Pressed = button.Species == species;
        }

        Select.Disabled = _profile.Species == species;

        var preview = _profile.WithSpecies(species);
        var coloration = _proto.Index(_proto.Index(species).SkinColoration).Strategy;
        preview = preview.WithCharacterAppearance(
            preview.Appearance.WithSkinColor(coloration.EnsureVerified(_profile.Appearance.SkinColor)));

        Mob.LoadPreview(preview, _job, false);
        JobLoadout.LoadPreview(preview, _job, true);

        DetailInfoContainer.DisposeAllChildren();
        _proto.TryIndex<SpeciesInfoPrototype>(species, out var info);
        if (info != null)
            AddProsCons(info);

        if (info?.Description is { } description)
        {
            using var file = _resources.ContentFileReadText(description);
            _parsing.TryAddMarkup(DetailInfoContainer, file.ReadToEnd());
        }
        else if (_proto.HasIndex<GuideEntryPrototype>(species.Id))
        {
            _parsing.TryAddMarkup(DetailInfoContainer, new ProtoId<GuideEntryPrototype>(species.Id));
        }
    }

    private void AddProsCons(SpeciesInfoPrototype info)
    {
        if (info.Pros.Count == 0 && info.Special.Count == 0 && info.Cons.Count == 0)
            return;

        AddLines(info.Pros, "#13f244");
        AddLines(info.Special, null);
        AddLines(info.Cons, "#d63636");
    }

    private void AddLines(List<LocId> lines, string? color)
    {
        foreach (var line in lines)
        {
            var text = "- " + Loc.GetString(line);
            DetailInfoContainer.AddChild(new RichTextLabel
            {
                Text = color == null ? text : $"[color={color}]{text}[/color]",
                Margin = new Thickness(4f, 2f),
            });
        }
    }

    private sealed class SpeciesButton(ProtoId<SpeciesPrototype> species) : Button
    {
        public readonly ProtoId<SpeciesPrototype> Species = species;
    }
}
