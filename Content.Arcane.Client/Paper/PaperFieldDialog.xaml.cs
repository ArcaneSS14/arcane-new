using Content.Arcane.Shared.Paper;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Arcane.Client.Paper;

[GenerateTypedNameReferences]
public sealed partial class PaperFieldDialog : DefaultWindow
{
    public event Action<string>? OnSubmitted;

    public PaperFieldDialog(PaperFieldKind kind, int limit)
    {
        RobustXamlLoader.Load(this);
        var check = kind == PaperFieldKind.Check;
        ValueInput.Visible = !check;
        CheckChoices.Visible = check;
        SaveButton.Visible = !check;
        CancelButton.OnPressed += _ => Close();
        BlankButton.OnPressed += _ => Submit("☐");
        CheckButton.OnPressed += _ => Submit("✔");
        CrossButton.OnPressed += _ => Submit("✖");
        SaveButton.OnPressed += _ => Submit(ValueInput.Text);
        ValueInput.OnTextEntered += _ => Submit(ValueInput.Text);
        ValueInput.OnTextChanged += _ => UpdateValidation();
        UpdateValidation();

        void UpdateValidation()
        {
            LimitWarning.Visible = limit >= 0 && ValueInput.Text.Length > limit;
            SaveButton.Disabled = string.IsNullOrEmpty(ValueInput.Text) || LimitWarning.Visible;
        }
    }

    private void Submit(string value)
    {
        if (string.IsNullOrEmpty(value) || LimitWarning.Visible)
            return;
        OnSubmitted?.Invoke(value);
        Close();
    }

    protected override void ExitedTree()
    {
        OnSubmitted = null;
        base.ExitedTree();
    }
}
