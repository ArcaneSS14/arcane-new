using Content.Arcane.Shared.Cards;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Arcane.Client.Cards;

[GenerateTypedNameReferences]
public sealed partial class PlayingCardsWindow : FancyWindow
{
    [Dependency] private IEntitySystemManager _systems = default!;
    public event Action<int, int>? DrawCard;

    public PlayingCardsWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void UpdateCards(PlayingCardsSnapshotMessage message)
    {
        Cards.RemoveAllChildren();
        var sprites = _systems.GetEntitySystem<SpriteSystem>();
        for (var i = 0; i < message.Cards.Count; i++)
        {
            var index = i;
            var face = message.Cards[i];
            var button = new Button { ToolTip = Loc.GetString(face.Name), MinSize = new Vector2(100, 120) };
            button.AddChild(new TextureRect {
                Texture = sprites.Frame0(new SpriteSpecifier.Rsi(new ResPath(PlayingCardsComponent.SpritePath), face.State)),
                TextureScale = new Vector2(3, 3), Stretch = TextureRect.StretchMode.KeepAspectCentered });
            button.OnPressed += _ => DrawCard?.Invoke(message.Revision, index);
            Cards.AddChild(button);
        }
    }
}
